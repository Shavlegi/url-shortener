#!/usr/bin/env node
/**
 * build-single-file.js — bundles the multi-file project into ONE Worker file
 * for the Cloudflare dashboard "Quick Edit" deployment path.
 *
 * Usage:  node scripts/build-single-file.js
 * Output: dist/worker-single-file.js
 *
 * What it does:
 *  - reads public/index.html, public/admin.html, public/styles.css,
 *    public/app.js, public/public.js, public/auth.js, public/qrcode.min.js
 *  - inlines them into the `EMBEDDED_FILES` constant of src/index.js
 *  - writes the result to dist/worker-single-file.js
 *
 * The bundled Worker serves the frontend from the embedded copy (no ASSETS
 * binding needed). The D1 binding must still be created in the dashboard
 * (Settings -> Variables -> D1 Database Bindings, name "DB") and the two
 * secrets set (ADMIN_PASSWORD_HASH, SESSION_SECRET). See README.md.
 */
import { readFileSync, writeFileSync, mkdirSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');

const FILES = {
  '/index.html': { path: 'public/index.html', type: 'text/html; charset=utf-8' },
  '/admin.html': { path: 'public/admin.html', type: 'text/html; charset=utf-8' },
  '/styles.css': { path: 'public/styles.css', type: 'text/css; charset=utf-8' },
  '/app.js': { path: 'public/app.js', type: 'text/javascript; charset=utf-8' },
  '/public.js': { path: 'public/public.js', type: 'text/javascript; charset=utf-8' },
  '/auth.js': { path: 'public/auth.js', type: 'text/javascript; charset=utf-8' },
  '/qrcode.min.js': { path: 'public/qrcode.min.js', type: 'text/javascript; charset=utf-8' },
};

const embedded = {};
for (const [url, info] of Object.entries(FILES)) {
  const body = readFileSync(join(root, info.path), 'utf8');
  embedded[url] = { body, type: info.type };
}

const src = readFileSync(join(root, 'src/index.js'), 'utf8');
const marker = 'const EMBEDDED_FILES = {};';
if (!src.includes(marker)) {
  console.error('ERROR: marker not found in src/index.js: ' + marker);
  process.exit(1);
}
const bundled =
  '// Bundled single-file Worker — generated by scripts/build-single-file.js\n' +
  '// Source of truth is the multi-file project (src/, public/). Do not edit this file by hand.\n' +
  src.replace(marker, 'const EMBEDDED_FILES = ' + JSON.stringify(embedded) + ';');

mkdirSync(join(root, 'dist'), { recursive: true });
writeFileSync(join(root, 'dist/worker-single-file.js'), bundled);
console.log('OK: dist/worker-single-file.js (' + bundled.length + ' bytes)');
